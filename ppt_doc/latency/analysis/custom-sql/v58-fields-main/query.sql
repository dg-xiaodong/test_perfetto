SELECT kind,
 COUNT(*) n,
 SUM(contract_version='latency.v1') cv,
 SUM(run_id IS NOT NULL) runid,
 SUM(stream_id IS NOT NULL) streamid,
 SUM(request_id IS NOT NULL) reqid,
 SUM(process_instance_id IS NOT NULL) pid_inst,
 SUM(stage_id IS NOT NULL) stageid,
 SUM(stage_instance_id IS NOT NULL) stageinst,
 SUM(attempt_id IS NOT NULL) attempt,
 SUM(queue_id IS NOT NULL) queueid,
 SUM(queue_visit_id IS NOT NULL) qvisit,
 SUM(link_id IS NOT NULL) linkid,
 SUM(from_instance IS NOT NULL) frominst,
 SUM(to_instance IS NOT NULL) toinst,
 SUM(status IS NOT NULL) status,
 SUM(expected_stage_count IS NOT NULL) exp_stage,
 SUM(expected_queue_count IS NOT NULL) exp_queue,
 SUM(expected_link_count IS NOT NULL) exp_link
FROM (
 SELECT s.name kind,
  CAST(EXTRACT_ARG(s.arg_set_id,'debug.contract_version') AS TEXT) contract_version,
  CAST(EXTRACT_ARG(s.arg_set_id,'debug.run_id') AS TEXT) run_id,
  CAST(EXTRACT_ARG(s.arg_set_id,'debug.stream_id') AS TEXT) stream_id,
  CAST(EXTRACT_ARG(s.arg_set_id,'debug.request_id') AS TEXT) request_id,
  CAST(EXTRACT_ARG(s.arg_set_id,'debug.process_instance_id') AS TEXT) process_instance_id,
  CAST(EXTRACT_ARG(s.arg_set_id,'debug.stage_id') AS TEXT) stage_id,
  CAST(EXTRACT_ARG(s.arg_set_id,'debug.stage_instance_id') AS TEXT) stage_instance_id,
  CAST(EXTRACT_ARG(s.arg_set_id,'debug.attempt_id') AS TEXT) attempt_id,
  CAST(EXTRACT_ARG(s.arg_set_id,'debug.queue_id') AS TEXT) queue_id,
  CAST(EXTRACT_ARG(s.arg_set_id,'debug.queue_visit_id') AS TEXT) queue_visit_id,
  CAST(EXTRACT_ARG(s.arg_set_id,'debug.link_id') AS TEXT) link_id,
  CAST(EXTRACT_ARG(s.arg_set_id,'debug.from_instance') AS TEXT) from_instance,
  CAST(EXTRACT_ARG(s.arg_set_id,'debug.to_instance') AS TEXT) to_instance,
  CAST(EXTRACT_ARG(s.arg_set_id,'debug.status') AS TEXT) status,
  CAST(EXTRACT_ARG(s.arg_set_id,'debug.expected_stage_count') AS TEXT) expected_stage_count,
  CAST(EXTRACT_ARG(s.arg_set_id,'debug.expected_queue_count') AS TEXT) expected_queue_count,
  CAST(EXTRACT_ARG(s.arg_set_id,'debug.expected_link_count') AS TEXT) expected_link_count
 FROM slice s WHERE s.category='rdk.latency'
) GROUP BY kind ORDER BY n DESC;
